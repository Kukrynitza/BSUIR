#!/usr/bin/env python3
"""Convert ``output/experiments.json`` into LaTeX macros and tables."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "output" / "experiments.json"
SECTIONS = ROOT / "mrzvis-report-3" / "sections"


def fmt(value, nd: int = 2) -> str:
    if value is None:
        return "---"
    if isinstance(value, float):
        if value == float("inf"):
            return r"$\infty$"
        text = f"{value:.{nd}f}"
        text = text.rstrip("0").rstrip(".") if "." in text else text
    else:
        text = str(value)
    return text.replace(".", "{,}")


def tval(value) -> str:
    return "---" if value is None else str(value)


def main() -> None:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    baselines = payload["baselines"]
    overlap = payload["overlap"]
    eps = payload["eps_by_image"]
    cfg = payload["config"]
    images = ("smooth", "contours", "texture")
    names = {"smooth": "Smooth", "contours": "Contours", "texture": "Texture"}
    labels = {
        "smooth": "Плавные переходы",
        "contours": "Контуры",
        "texture": "Текстура",
    }

    macros: list[str] = [
        "% auto-generated by make_report_data.py",
        rf"\newcommand{{\Tmax}}{{{cfg['epochs']}}}",
        rf"\newcommand{{\Pbase}}{{{cfg['p_base']}}}",
        rf"\newcommand{{\BlockSize}}{{{cfg['block']}}}",
        rf"\newcommand{{\StepSize}}{{{cfg['step']}}}",
    ]

    for image in images:
        row = baselines[image]
        suffix = names[image]
        macros += [
            rf"\newcommand{{\B{suffix}E}}{{{fmt(row['final_error'], 2)}}}",
            rf"\newcommand{{\B{suffix}MSE}}{{{fmt(row['mse_norm'], 6)}}}",
            rf"\newcommand{{\B{suffix}PIXMSE}}{{{fmt(row['mse_pixels'], 2)}}}",
            rf"\newcommand{{\B{suffix}PSNR}}{{{fmt(row['psnr_db'], 2)}}}",
            rf"\newcommand{{\B{suffix}K}}{{{fmt(row['K_bytes'], 3)}}}",
            rf"\newcommand{{\B{suffix}Z}}{{{fmt(row['Z'], 2)}}}",
            rf"\newcommand{{\B{suffix}QT}}{{{row['QT']}}}",
            rf"\newcommand{{\B{suffix}T}}{{{fmt(row['train_time_s'], 2)}}}",
            rf"\newcommand{{\Eps{suffix}}}{{{fmt(eps[image], 2)}}}",
        ]

    first = baselines[images[0]]
    macros += [
        rf"\newcommand{{\Zbase}}{{{fmt(first['Z'], 2)}}}",
        rf"\newcommand{{\Kbase}}{{{fmt(first['K_bytes'], 3)}}}",
        rf"\newcommand{{\Zoverlap}}{{{fmt(overlap[images[0]]['Z'], 2)}}}",
        rf"\newcommand{{\Koverlap}}{{{fmt(overlap[images[0]]['K_bytes'], 3)}}}",
    ]

    common = payload["family_c"][0]
    macros += [
        rf"\newcommand{{\CommonMSE}}{{{fmt(cfg['common_mse_target'], 3)}}}",
        rf"\newcommand{{\EpsCommon}}{{{fmt(common['eps_common'], 2)}}}",
        rf"\newcommand{{\Qoverlap}}{{{overlap[images[0]]['Q']}}}",
        rf"\newcommand{{\Qbase}}{{{first['Q']}}}",
    ]
    (SECTIONS / "auto_numbers.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")

    # Table: reference runs.
    lines = [
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Опорные запуски (без перекрытия, $p=16$, $\beta=1$)}",
        r"\label{tab:results}",
        r"\small",
        r"\begin{tabular}{@{}lcccccccc@{}}",
        r"\hline",
        r"Изображение & $Q$ & $K$ & $Z$ & $T$ & $E$ & $\mathrm{MSE}_n$ & PSNR, дБ & $t$, с \\",
        r"\hline",
    ]
    for image in images:
        row = baselines[image]
        lines.append(
            f"{labels[image]} & {row['Q']} & {fmt(row['K_bytes'], 3)} & "
            f"{fmt(row['Z'], 2)} & {row['epochs_done']} & {fmt(row['final_error'], 2)} & "
            f"{fmt(row['mse_norm'], 6)} & {fmt(row['psnr_db'], 2)} & "
            f"{fmt(row['train_time_s'], 2)} \\\\"
        )
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    (SECTIONS / "tab_results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Table: overlap comparison.
    lines = [
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Влияние перекрытия блоков ($p=16$)}",
        r"\label{tab:overlap}",
        r"\begin{tabular}{@{}lcccccc@{}}",
        r"\hline",
        r"Изображение & $s_h=s_w$ & $Q$ & $K$ & $T$ & $\mathrm{MSE}_n$ & PSNR, дБ \\",
        r"\hline",
    ]
    for image in images:
        for tag, row in (("8", baselines[image]), ("4", overlap[image])):
            lines.append(
                f"{labels[image]} & {tag} & {row['Q']} & {fmt(row['K_bytes'], 3)} & "
                f"{row['epochs_done']} & {fmt(row['mse_norm'], 6)} & "
                f"{fmt(row['psnr_db'], 2)} \\\\"
            )
        lines.append(r"\hline")
    lines += [r"\end{tabular}", r"\end{table}"]
    (SECTIONS / "tab_overlap.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Table: family A.
    betas = cfg["betas"]
    lines = [
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Семейство A: число эпох при разных $\beta$}",
        r"\label{tab:family-a}",
        r"\begin{tabular}{@{}lccc@{}}",
        r"\hline",
        r"$\beta$ & Плавные переходы & Контуры & Текстура \\",
        r"\hline",
    ]
    for beta in betas:
        cells = []
        for image in images:
            row = next(
                r for r in payload["family_a"] if r["image"] == image and abs(r["beta"] - beta) < 1e-12
            )
            cells.append(tval(row["T"]))
        lines.append(f"{fmt(beta, 2)} & " + " & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    (SECTIONS / "tab_family_a.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Table: family B.
    lines = [
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Семейство B: число эпох при разных $p$ и $K$}",
        r"\label{tab:family-b}",
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\hline",
        r"$p$ & $K$ & Плавные переходы & Контуры & Текстура \\",
        r"\hline",
    ]
    for p in cfg["p_values"]:
        row0 = next(r for r in payload["family_b"] if r["p"] == p)
        cells = []
        for image in images:
            row = next(
                r for r in payload["family_b"] if r["image"] == image and r["p"] == p
            )
            cells.append(tval(row["T"]))
        lines.append(f"{p} & {fmt(row0['K_bytes'], 3)} & " + " & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    (SECTIONS / "tab_family_b.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Table: family C.
    lines = [
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Семейство C: зависимость от типа изображения}",
        r"\label{tab:family-c}",
        r"\begin{tabular}{@{}lcccccc@{}}",
        r"\hline",
        r"Изображение & $\varepsilon_i$ & $T_i$ & $\varepsilon_{\text{общ}}$ & $T_{\text{общ}}$ & $\mathrm{MSE}_n$ & $K$ \\",
        r"\hline",
    ]
    for row in payload["family_c"]:
        image = row["image"]
        lines.append(
            f"{labels[image]} & {fmt(row['eps_individual'], 2)} & {tval(row['T_ind'])} & "
            f"{fmt(row['eps_common'], 2)} & {tval(row['T_common'])} & "
            f"{fmt(row['mse_norm'], 6)} & {fmt(row['K_bytes'], 3)} \\\\"
        )
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    (SECTIONS / "tab_family_c.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Table: family D as longtable.
    lines = [
        r"\begin{longtable}{@{}lll@{}}",
        r"\caption{Семейство D: число эпох при разных порогах $\varepsilon$}\label{tab:family-d}\\",
        r"\hline",
        r"Изображение & $\varepsilon$ & $T$ \\",
        r"\hline",
        r"\endfirsthead",
        r"\hline",
        r"Изображение & $\varepsilon$ & $T$ \\",
        r"\hline",
        r"\endhead",
    ]
    for image in images:
        for row in sorted(
            (r for r in payload["family_d"] if r["image"] == image),
            key=lambda r: r["eps"],
            reverse=True,
        ):
            lines.append(
                f"{labels[image]} & {fmt(row['eps'], 3)} & {tval(row['T'])} \\\\"
            )
        lines.append(r"\hline")
    lines += [r"\end{longtable}"]
    (SECTIONS / "tab_family_d.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("LaTeX data written")


if __name__ == "__main__":
    main()
