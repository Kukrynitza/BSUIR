PATTERNS: dict[str, tuple[str, ...]] = {**_LETTERS, **_DIGITS}


def pattern_names(letters: bool = True, digits: bool = True) -> list[str]:
    names: list[str] = []
    if letters:
        names.extend(_LETTERS.keys())
    if digits:
        names.extend(_DIGITS.keys())
    return names


def get_pattern(name: str) -> np.ndarray:
    rows = PATTERNS[name]
    if len(rows) != GRID or any(len(r) != GRID for r in rows):
        raise ValueError(f"bad pattern {name}")
    grid = np.array([[1.0 if ch == "#" else -1.0 for ch in row] for row in rows])
    return grid.reshape(-1)


def patterns_matrix(names: list[str]) -> np.ndarray:
    return np.stack([get_pattern(name) for name in names])


def to_pm1(grid: np.ndarray) -> np.ndarray:
    return np.where(grid >= 0, 1.0, -1.0)


def add_noise(x: np.ndarray, p: float, rng: np.random.Generator) -> np.ndarray:
    if not 0.0 <= p <= 1.0:
        raise ValueError(f"bad noise {p}")
    y = np.array(x, dtype=np.float64, copy=True)
    mask = rng.random(y.shape) < p
    y[mask] = -y[mask]
    return y


def repeat_patterns(X: np.ndarray, k: int) -> np.ndarray:
    if k < 1:
        raise ValueError(f"bad k={k}")
    return np.tile(X, (k, 1))


def grid_image(x: np.ndarray) -> np.ndarray:
    g = x.reshape(GRID, GRID)
    return np.where(g > 0, 0, 255).astype(np.uint8)
